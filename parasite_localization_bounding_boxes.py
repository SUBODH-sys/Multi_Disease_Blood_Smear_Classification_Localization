def predict_per_class_threshold(image_path, model, per_class_conf,
                                 iou_threshold=0.45):
    """
    Run inference at a very low global conf (0.10) to get all
    candidate boxes, then filter each by its class-specific threshold.

    This lets different classes have different sensitivity levels
    without retraining anything.
    """
    # Get all candidates at low global threshold
    result = model.predict(
        image_path,
        conf    = 0.10,   # Very low — we filter manually below
        iou     = iou_threshold,
        imgsz   = 640,
        verbose = False
    )[0]

    img    = Image.open(image_path).convert("RGB")
    iw, ih = img.size

    kept  = []
    total_candidates = len(result.boxes)

    for box in result.boxes:
        cid  = int(box.cls[0])
        conf = float(box.conf[0])

        # Apply per-class threshold
        min_conf = per_class_conf.get(cid, 0.25)
        if conf < min_conf:
            continue

        x1, y1, x2, y2 = box.xyxy[0].cpu().numpy()
        kept.append({
            "class_id"  : cid,
            "class_name": CLASS_NAMES[cid],
            "confidence": round(conf, 4),
            "x1": int(x1), "y1": int(y1),
            "x2": int(x2), "y2": int(y2),
        })

    return kept, total_candidates


