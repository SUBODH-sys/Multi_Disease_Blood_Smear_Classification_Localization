def oversample_minority_class(output_base, disease="malaria",
                               img_ext=".jpg", factor=3):
    """
    Duplicate images of the minority class in the training set.
    factor=3 means malaria images appear 3x more often than once.

    This is simpler than weighted loss — just more copies of the
    underrepresented class in the training folder.
    """
    img_dir = os.path.join(output_base, "images", "train")
    lbl_dir = os.path.join(output_base, "labels", "train")

    # Find all training images that contain class 1 (malaria)
    malaria_imgs = []
