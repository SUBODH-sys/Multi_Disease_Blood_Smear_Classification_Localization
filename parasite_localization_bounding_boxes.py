def read_yolo_label(label_path):
    """
    Read a YOLO format label file.
    Each line: class_id  x_center  y_center  width  height
    All values are normalized (0 to 1).
    """
    boxes = []
    if not os.path.exists(label_path):
        return boxes

    with open(label_path, "r") as f:
        for line in f.readlines():
            line = line.strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) < 5:
                print(f"  Skipping malformed line: {line}")
                continue
            class_id = int(float(parts[0]))
            x_center = float(parts[1])
            y_center = float(parts[2])
            width    = float(parts[3])
            height   = float(parts[4])
            boxes.append((class_id, x_center, y_center, width, height))
    return boxes


def visualize_annotations(image_path, label_path, class_names, title=""):
    """
    Draw bounding boxes on an image and display it.
    Converts YOLO normalized coords back to pixel coords for drawing.
    """
    # Load image
    img = Image.open(image_path).convert("RGB")
    img_w, img_h = img.size

    # Read labels
    boxes = read_yolo_label(label_path)

    # Setup plot
    fig, ax = plt.subplots(1, 1, figsize=(8, 8))
    ax.imshow(img)
    ax.set_title(f"{title}\n{os.path.basename(image_path)} — {len(boxes)} objects",
                 fontsize=11)
    ax.axis("off")

    # Color per class
    colors = {0: "lime", 1: "red", 2: "cyan", 3: "yellow"}

    for (class_id, xc, yc, bw, bh) in boxes:
        # Convert YOLO normalized → pixel coords
        x1 = (xc - bw / 2) * img_w
        y1 = (yc - bh / 2) * img_h
        box_w = bw * img_w
        box_h = bh * img_h

        color = colors.get(class_id, "white")
        label = class_names.get(class_id, f"class_{class_id}")

        # Draw rectangle
        rect = patches.Rectangle(
            (x1, y1), box_w, box_h,
            linewidth=1.5,
            edgecolor=color,
            facecolor="none"
        )
        ax.add_patch(rect)

        # Draw label text
        ax.text(
            x1, y1 - 3, label,
            color=color,
            fontsize=8,
            fontweight="bold",
            bbox=dict(boxstyle="round,pad=0.1", facecolor="black", alpha=0.5)
        )

    plt.tight_layout()
    plt.show()
    return boxes


