from collections import defaultdict

def compute_class_confusion(model, label_dir, img_dir, class_names, conf_threshold=0.25, iou_threshold=0.45):
    """
    For every ground truth box, find the best matching predicted box
    (by IoU). Record: what was GT class? What did model predict?

    Returns a confusion dict: { (gt_class, pred_class): count }
    """
    def box_iou(b1, b2):
        """Compute IoU between two boxes [x1,y1,x2,y2]."""
        xi1 = max(b1[0], b2[0])
        yi1 = max(b1[1], b2[1])
        xi2 = min(b1[2], b2[2])
        yi2 = min(b1[3], b2[3])
        inter = max(0, xi2 - xi1) * max(0, yi2 - yi1)
        area1 = (b1[2]-b1[0]) * (b1[3]-b1[1])
        area2 = (b2[2]-b2[0]) * (b2[3]-b2[1])
        union = area1 + area2 - inter
        return inter / union if union > 0 else 0.0

    confusion = defaultdict(int)
    lbl_files = glob.glob(os.path.join(label_dir, "*.txt"))

    for lf in lbl_files:
        base = os.path.splitext(os.path.basename(lf))[0]
        imgs = (
            glob.glob(os.path.join(img_dir, base + ".jpg")) +
            glob.glob(os.path.join(img_dir, base + ".jpeg"))
        )
        if not imgs:
            continue

        img    = Image.open(imgs[0])
        img_w, img_h = img.size

        # Ground truth boxes (pixel coords)
        gt = []
        with open(lf) as f:
            for line in f:
                parts = line.strip().split()
                if len(parts) < 5:
                    continue
                cid  = int(parts[0])
                xc, yc, bw, bh = map(float, parts[1:5])
                x1 = (xc - bw/2) * img_w
                y1 = (yc - bh/2) * img_h
                x2 = (xc + bw/2) * img_w
                y2 = (yc + bh/2) * img_h
                gt.append((cid, [x1, y1, x2, y2]))

        # Predictions
        preds_raw = model.predict(imgs[0], conf=conf_threshold, verbose=False)[0]
        preds = []
        for box in preds_raw.boxes:
            x1, y1, x2, y2 = box.xyxy[0].cpu().numpy()
            preds.append((int(box.cls[0]), float(box.conf[0]), [x1,y1,x2,y2]))

        # Match each GT box to the best-IoU prediction
        for (gt_cid, gt_box) in gt:
            best_iou    = 0.0
            best_pred   = None
            for (pred_cid, pred_conf, pred_box) in preds:
                iou = box_iou(gt_box, pred_box)
                if iou > best_iou:
                    best_iou  = iou
                    best_pred = pred_cid

            if best_iou >= iou_threshold and best_pred is not None:
                confusion[(gt_cid, best_pred)] += 1  # matched
            else:
                confusion[(gt_cid, -1)] += 1          # missed (false negative)

    return confusion


