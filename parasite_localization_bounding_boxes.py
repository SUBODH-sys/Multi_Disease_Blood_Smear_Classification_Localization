    for lbl_path in all_lbls:
        boxes = read_yolo_label(lbl_path)
        if any(cid == 1 for (cid, *_) in boxes):   # class 1 = malaria
            base  = os.path.splitext(os.path.basename(lbl_path))[0]
            img_candidates = (
                glob.glob(os.path.join(img_dir, base + ".jpg")) +
                glob.glob(os.path.join(img_dir, base + ".jpeg"))
            )
            if img_candidates:
                malaria_imgs.append((img_candidates[0], lbl_path))

    print(f"Found {len(malaria_imgs)} malaria training images.")
    print(f"Duplicating each {factor - 1} extra time(s)...\n")

    added = 0
    for (img_path, lbl_path) in malaria_imgs:
        ext = os.path.splitext(img_path)[1]
        for copy_n in range(1, factor):
            # Find the index from the existing filename to continue numbering
            # New name: original_name + _aug_N
            base = os.path.splitext(os.path.basename(img_path))[0]
            new_base     = f"{base}_aug{copy_n}"
            new_img_path = os.path.join(img_dir, new_base + ext)
            new_lbl_path = os.path.join(lbl_dir, new_base + ".txt")

            shutil.copy2(img_path, new_img_path)
            shutil.copy2(lbl_path, new_lbl_path)
            added += 1

    print(f"Added {added} malaria image copies to training set.")
    print(f"New malaria training count: {len(malaria_imgs) * factor}")

    # Verify new totals
    n_imgs = len(glob.glob(os.path.join(img_dir, "*.jpg")))
    n_lbls = len(glob.glob(os.path.join(lbl_dir, "*.txt")))
    print(f"\nUpdated train set: {n_imgs} images, {n_lbls} labels")


