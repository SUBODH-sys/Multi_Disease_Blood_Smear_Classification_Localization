def remap_and_copy(src_img, src_lbl, dst_img_dir, dst_lbl_dir,
                   class_map, img_idx):
    """
    Copy one image and write a remapped label file.

    class_map: dict { "raw_id_as_str": new_unified_int }
    img_idx:   unique integer to prevent filename collisions across datasets
    """
    ext       = os.path.splitext(src_img)[1]
    base_name = f"img_{img_idx:06d}"

    # ── Copy image ───────────────────────────────────────────
    shutil.copy2(src_img, os.path.join(dst_img_dir, base_name + ext))

    # ── Write remapped label ─────────────────────────────────
    dst_lbl_path = os.path.join(dst_lbl_dir, base_name + ".txt")
    boxes = read_yolo_label(src_lbl)

    with open(dst_lbl_path, "w") as f:
        for (raw_cid, xc, yc, bw, bh) in boxes:
            key = str(raw_cid)
            if key not in class_map:
                # Unknown class ID — skip with a warning
                print(f"  WARNING: Unknown class id {raw_cid} in {src_lbl} — skipped")
                continue
            new_cid = class_map[key]
            f.write(f"{new_cid} {xc:.6f} {yc:.6f} {bw:.6f} {bh:.6f}\n")


def build_unified_dataset(dataset_paths, disease_class_map, output_base,
                           train_ratio=0.70, val_ratio=0.20, test_ratio=0.10,
                           seed=42):
    """
    Merge all disease datasets into one unified YOLO dataset
    with correct class remapping and stratified splits.

    Split strategy: 70% train / 20% val / 10% test
    Each disease is split independently before merging, so every
    disease appears in every split at the correct proportion.
    This is called STRATIFIED SPLITTING — important because if we
    shuffled everything together first, the tiny malaria set could
    accidentally end up mostly in val/test.
    """
    random.seed(seed)
    img_counter  = 0
    split_counts = {"train": {}, "val": {}, "test": {}}

    for disease, paths in dataset_paths.items():
        print(f"\n{'─'*50}")
        print(f"Processing: {disease.upper()}")
        print(f"{'─'*50}")

        img_files = sorted(
            glob.glob(os.path.join(paths["images"], "*.jpg"))  +
            glob.glob(os.path.join(paths["images"], "*.jpeg")) +
            glob.glob(os.path.join(paths["images"], "*.png"))
        )

        if not img_files:
            print(f"  No images found — skipping.")
            continue

        random.shuffle(img_files)
        n       = len(img_files)
        n_train = int(n * train_ratio)
        n_val   = int(n * val_ratio)
        # Everything remaining goes to test

        splits = {
            "train": img_files[:n_train],
            "val":   img_files[n_train : n_train + n_val],
            "test":  img_files[n_train + n_val:],
        }

        cmap = disease_class_map[disease]

        for split_name, files in splits.items():
            dst_img = os.path.join(output_base, "images", split_name)
            dst_lbl = os.path.join(output_base, "labels", split_name)
            os.makedirs(dst_img, exist_ok=True)
            os.makedirs(dst_lbl, exist_ok=True)

            for img_path in files:
                lbl_path = os.path.join(
                    paths["labels"],
                    os.path.splitext(os.path.basename(img_path))[0] + ".txt"
                )
                remap_and_copy(img_path, lbl_path,
                               dst_img, dst_lbl, cmap, img_counter)
                img_counter += 1

            split_counts[split_name][disease] = len(files)
            print(f"  {split_name:5s} → {len(files):4d} images")

    return split_counts


