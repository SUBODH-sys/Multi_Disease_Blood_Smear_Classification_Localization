    gt_ids   = [b[0] for b in gt_boxes]
    pred_ids = [b[0] for b in pred_boxes]
    print(f"  GT classes   : {[class_names[c] for c in gt_ids]}")
    print(f"  Pred classes : {[class_names[c] for c in pred_ids]}")
    print()


